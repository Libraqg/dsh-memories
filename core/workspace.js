// Port of codex-rs/memories/write/src/workspace.rs (V1 artifacts).

import { readFile, rm, stat, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

import { diffSinceLatestInit, ensureGitBaselineRepository, resetGitRepository } from './git-baseline.js'
import { ensureLayout, removeMemorySymlinks } from './storage.js'

export const WORKSPACE_DIFF_FILENAME = 'phase2_workspace_diff.md'
const WORKSPACE_DIFF_MAX_BYTES = 4 * 1024 * 1024

async function removeWorkspaceDiff(root) {
  await rm(join(root, WORKSPACE_DIFF_FILENAME), { force: true })
}

export async function prepareMemoryWorkspace(root) {
  await ensureLayout(root)
  await removeWorkspaceDiff(root)
  await ensureGitBaselineRepository(root)
}

export async function memoryWorkspaceDiff(root) {
  await removeWorkspaceDiff(root)
  return diffSinceLatestInit(root)
}

function boundedDiff(diff) {
  const buffer = Buffer.from(diff, 'utf8')
  if (buffer.length <= WORKSPACE_DIFF_MAX_BYTES) return diff.endsWith('\n') ? diff : `${diff}\n`
  let end = WORKSPACE_DIFF_MAX_BYTES
  while (end > 0 && (buffer[end] & 0xc0) === 0x80) end -= 1
  const head = buffer.subarray(0, end).toString('utf8')
  return `${head}${head.endsWith('\n') ? '' : '\n'}\n[workspace diff truncated at ${WORKSPACE_DIFF_MAX_BYTES} bytes]\n`
}

export function renderWorkspaceDiffFile(diff) {
  let rendered =
    '# Memory Workspace Diff\n\n' +
    'Generated by Codex before Phase 2 memory consolidation. Read this file first and do not edit it.\n\n' +
    '## Status\n'
  if (diff.changes.length === 0) return `${rendered}- none\n`
  for (const change of diff.changes) rendered += `- ${change.status} ${change.path}\n`
  return `${rendered}\n## Diff\n\n\`\`\`diff\n${boundedDiff(diff.unifiedDiff)}\`\`\`\n`
}

export async function writeWorkspaceDiff(root, diff) {
  await writeFile(join(root, WORKSPACE_DIFF_FILENAME), renderWorkspaceDiffFile(diff))
}

/** Removes the prompt artifact first so deleted content cannot survive in the baseline. */
export async function resetMemoryWorkspaceBaseline(root) {
  await removeWorkspaceDiff(root)
  await resetGitRepository(root)
}

/** @throws when a finished consolidation left missing or unsafe artifacts */
export async function validateConsolidationArtifacts(root) {
  const removed = await removeMemorySymlinks(root)
  if (removed !== 0) throw new Error(`removed ${removed} symbolic links from consolidated memory workspace`)
  if (!(await stat(join(root, 'MEMORY.md'))).isFile()) throw new Error('MEMORY.md is not a file')
  const summary = await readFile(join(root, 'memory_summary.md'), 'utf8')
  if (summary.split(/\r?\n/, 1)[0] !== 'v1') throw new Error('memory_summary.md does not start with v1')
}
